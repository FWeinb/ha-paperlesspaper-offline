export type Localize = (key: Key, vars?: Record<string, string | number>) => string;

export function localizer(hass?: HomeAssistant): Localize {
  const table: Record<Key, string> = hass?.language?.startsWith("de") ? de : en;
  return (key, vars) => {
    let text = table[key] ?? en[key] ?? key;
    for (const [name, value] of Object.entries(vars ?? {})) {
      text = text.replace(`{${name}}`, String(value));
    }
    return text;
  };
}

/** "5 minutes ago" in the user's language. */
export function relativeTime(iso: string | null, hass: HomeAssistant, never: string): string {
  if (!iso) return never;
  const seconds = Math.round((new Date(iso).getTime() - Date.now()) / 1000);
  const fmt = new Intl.RelativeTimeFormat(hass.language || "en", { numeric: "auto" });
  const steps: [number, Intl.RelativeTimeFormatUnit][] = [
    [60, "second"],
    [60, "minute"],
    [24, "hour"],
    [7, "day"],
    [Number.POSITIVE_INFINITY, "week"],
  ];
  let value = seconds;
  for (const [size, unit] of steps) {
    if (Math.abs(value) < size) return fmt.format(value, unit);
    value = Math.round(value / size);
  }
  return fmt.format(value, "week");
}
